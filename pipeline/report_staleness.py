"""Write docs/staleness-report.md: growth per RDO, how far barangays move in the ranking once values are
projected to today, and the biggest movers. Run after build.py."""
import csv
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REVIEW = Path(__file__).resolve().parent / 'review'
OUT = ROOT / 'docs' / 'staleness-report.md'
LONG_YEARS = 10  # same threshold as the map's 'rough' warning (src/main.ts)


def ranks(props: list[dict], key: str) -> dict[str, int]:
    order = sorted(props, key=lambda p: -p[key])
    return {p['id']: i + 1 for i, p in enumerate(order)}


def money(v: float) -> str:
    return f'₱{v:,.0f}'


def main() -> None:
    meta = json.loads((ROOT / 'public' / 'data' / 'meta.json').read_text())
    feats = json.loads((ROOT / 'public' / 'data' / 'zonal.geojson').read_text())['features']
    own = [f['properties'] for f in feats if f['properties']['q'] == 'barangay_data' and f['properties'].get('typ_a')]
    raw, adj = ranks(own, 'typ'), ranks(own, 'typ_a')
    moves = sorted(own, key=lambda p: -abs(raw[p['id']] - adj[p['id']]))
    shifts = [abs(raw[p['id']] - adj[p['id']]) for p in own]
    n = len(own)
    tenth = n // 10
    moved_any = sum(s > 0 for s in shifts)
    moved_10pct = sum(s >= tenth for s in shifts)
    uplift = [p['typ_a'] / p['typ'] for p in own]
    growth = list(csv.DictReader(open(REVIEW / 'growth_by_rdo.csv', encoding='utf-8')))

    lines = [
        '# Staleness adjustment report',
        '',
        f"Values projected to {meta['adjusted_to']}. Each barangay's typical value is grown from the effectivity date "
        "of the schedule its values were set in, at its RDO's median annual growth. Growth is measured on the same "
        'street in the same barangay across consecutive revisions, never on Department Order averages.',
        '',
        '## Growth rate per RDO',
        '',
        '| RDO | Annual growth | Street pairs | Rising | Revisions compared | Flags |',
        '|---|---:|---:|---:|---|---|',
    ]
    for g in growth:
        rate = f"{float(g['annual_rate']):.1%}" if g['annual_rate'] else 'n/a'
        if g['source'] != 'rdo':
            rate += f" ({g['source']})"
        lines.append(f"| {g['rdo'].replace('RDO-', '')} | {rate} | {g['pairs']} | {float(g['share_rising']):.0%} | "
                     f"{g['transitions'].split('; ')[0]} | {g['flags']} |")
    lines += [
        '',
        '## How much the ranking moves',
        '',
        f'- {n:,} barangays have their own values and a growth rate.',
        f'- Median uplift from the scheduled to the adjusted value: {statistics.median(uplift):.2f}x '
        f'(middle half {statistics.quantiles(uplift, n=4)[0]:.2f}x to {statistics.quantiles(uplift, n=4)[2]:.2f}x).',
        f'- {moved_any:,} barangays change rank; {moved_10pct:,} move by a tenth of the list or more ({tenth:,}+ places); '
        f'the median move is {statistics.median(shifts):.0f} places.',
    ]

    def table(rows):
        out = ['| Barangay | Values set in | Growth used | Years projected | Typical, scheduled | Typical, adjusted | Rank |',
               '|---|---|---:|---:|---:|---:|---|']
        for p in rows:
            set_in = p['since'] if p.get('since') else f"{p.get('do', '')}, {p.get('eff', '')}"
            out.append(f"| {p['n']}, {p['c']} | {set_in} | {p['g']:.1%} | {p['yrs']:.0f} | {money(p['typ'])} | "
                       f"{money(p['typ_a'])} | {raw[p['id']]:,} → {adj[p['id']]:,} |")
        return out

    long = [p for p in own if p['yrs'] > LONG_YEARS]
    lines += [
        '',
        '## Five biggest changes',
        '',
        *table(moves[:5]),
        '',
        f'All five take their value from an old schedule: their RDO\'s newer schedule either lists them under a name '
        f'not yet aliased or does not list them at all (see `pipeline/review/plausibility.csv`), so a recent growth '
        f'rate is applied over many years. {len(long)} barangays are projected over more than {LONG_YEARS} years; '
        f'the map marks them as rough.',
        '',
        f'## Five biggest changes among barangays projected {LONG_YEARS} years or less',
        '',
        *table([p for p in moves if p['yrs'] <= LONG_YEARS][:5]),
    ]
    lines += ['', '_Generated by `pipeline/report_staleness.py`._', '']
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print('\n'.join(lines[-12:-2]))


if __name__ == '__main__':
    main()
