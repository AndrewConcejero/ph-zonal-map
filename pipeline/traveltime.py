"""Estimated car travel time from every barangay to a set of preset destinations, for the map's travel-time view.

Self-hosted OSRM (Homebrew osrm-backend) on the Geofabrik Philippines extract (© OpenStreetMap contributors, ODbL).
OSRM keeps one speed per road segment, so each period is its own routing dataset: the stock car profile with speeds
scaled by road class, and again by distance from central Metro Manila. The multipliers below are first guesses until
they are calibrated against logged trips (docs/travel-time-design.md §2.3). Until then the published range is a fixed
band around each estimate (RANGE), and the view says the model is uncalibrated.

  am   weekday morning peak, barangay -> destination
  pm   weekday evening peak, destination -> barangay (the trip home)
  off  midday / late evening, barangay -> destination

Usage: python -m pipeline.traveltime build   -> cache/osrm/<period>/ (slow: one OSRM extract per period)
       python -m pipeline.traveltime table   -> public/data/travel/index.json + one <preset>.json per destination
       python -m pipeline.traveltime all
"""
from __future__ import annotations

import csv
import json
import os
import socket
import statistics
import subprocess
import sys
import time
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

from shapely.geometry import shape

ROOT = Path(__file__).resolve().parent.parent
PBF = ROOT / 'cache' / 'osm' / 'philippines-latest.osm.pbf'
WORK = ROOT / 'cache' / 'osrm'
OUT = ROOT / 'public' / 'data' / 'travel'
PRESETS = Path(__file__).with_name('traveltime_presets.csv')
OSRM_BIN = Path(os.environ.get('OSRM_BIN', '/opt/homebrew/bin'))
PROFILES = Path(os.environ.get('OSRM_PROFILES', '/opt/homebrew/share/osrm/profiles'))

# speed multiplier by OSM highway class (applied after the car profile's own speeds and maxspeed tags)
CLASS = {
    'am':  {'motorway': 0.75, 'trunk': 0.55, 'primary': 0.50, 'secondary': 0.55, 'tertiary': 0.60, 'other': 0.70},
    'pm':  {'motorway': 0.65, 'trunk': 0.45, 'primary': 0.42, 'secondary': 0.48, 'tertiary': 0.55, 'other': 0.65},
    'off': {'motorway': 0.95, 'trunk': 0.75, 'primary': 0.70, 'secondary': 0.75, 'tertiary': 0.80, 'other': 0.85},
}
# and by zone: rings around central Metro Manila (km from CENTRE, multiplier); beyond the last ring, 1.0
CENTRE = (121.03, 14.58)  # near Guadalupe, between Makati, BGC, Ortigas and Manila
ZONES = {'am': [(7, 0.75), (18, 0.85)], 'pm': [(7, 0.70), (18, 0.80)], 'off': [(7, 0.85), (18, 0.92)]}
RANGE = (0.85, 1.35)  # uncalibrated band: low = good day, high = bad day
SNAP_KMH = 15  # the leg from a barangay's centre to the nearest routable road
PERIODS = {'am': 'Weekday morning peak, to the destination',
           'pm': 'Weekday evening peak, from the destination home',
           'off': 'Off-peak (midday or late evening), to the destination'}
PORT = 5731

PROFILE = """-- generated by pipeline/traveltime.py for period '{period}'; do not edit
package.path = '{profiles}/?.lua;' .. package.path
local car = require('car')

local CLASS = {{ {classes} }}
local OTHER = {other}
local ZONES = {{ {zones} }}
local LON0, LAT0 = {lon0}, {lat0}

local function multiplier(highway)
  if not highway then return 1.0 end
  return CLASS[(highway:gsub('_link$', ''))] or OTHER
end

local function zone_factor(lon, lat)
  local dx = (lon - LON0) * 111.32 * math.cos(math.rad(LAT0))
  local dy = (lat - LAT0) * 110.57
  local d = math.sqrt(dx * dx + dy * dy)
  for _, z in ipairs(ZONES) do
    if d <= z[1] then return z[2] end
  end
  return 1.0
end

function process_way(profile, way, result, relations)
  car.process_way(profile, way, result, relations)
  local m = multiplier(way:get_value_by_key('highway'))
  if result.forward_speed > 0 then result.forward_speed = result.forward_speed * m end
  if result.backward_speed > 0 then result.backward_speed = result.backward_speed * m end
  if result.forward_rate > 0 then result.forward_rate = result.forward_rate * m end
  if result.backward_rate > 0 then result.backward_rate = result.backward_rate * m end
end

function process_segment(profile, segment)
  local f = zone_factor((segment.source.lon + segment.target.lon) / 2, (segment.source.lat + segment.target.lat) / 2)
  segment.duration = segment.duration / f
  segment.weight = segment.weight / f
end

return {{
  setup = car.setup,
  process_way = process_way,
  process_node = car.process_node,
  process_turn = car.process_turn,
  process_segment = process_segment
}}
"""


def write_profile(period: str, path: Path) -> None:
    c = CLASS[period]
    path.write_text(PROFILE.format(
        period=period, profiles=PROFILES, other=c['other'], lon0=CENTRE[0], lat0=CENTRE[1],
        classes=', '.join(f'{k} = {v}' for k, v in c.items() if k != 'other'),
        zones=', '.join(f'{{{r}, {f}}}' for r, f in ZONES[period])))


def run(*args: str | Path, cwd: Path) -> None:
    print('  $', ' '.join(str(a) for a in args), flush=True)
    subprocess.run([str(a) for a in args], check=True, stdout=subprocess.DEVNULL, cwd=cwd)


def build(periods=tuple(PERIODS)) -> None:
    if not PBF.exists():
        sys.exit(f'missing {PBF}: download https://download.geofabrik.de/asia/philippines-latest.osm.pbf there')
    for period in periods:
        d = WORK / period
        d.mkdir(parents=True, exist_ok=True)
        pbf = d / 'ph.osm.pbf'
        if not pbf.exists():
            os.link(PBF, pbf)  # hard link: same file, so OSRM writes its outputs next to it
        profile = d / f'car_{period}.lua'
        write_profile(period, profile)
        t = time.time()
        # relative paths from inside the folder: osrm-extract rejects a --profile path containing a space
        run(OSRM_BIN / 'osrm-extract', '-p', profile.name, pbf.name, cwd=d)
        run(OSRM_BIN / 'osrm-partition', 'ph.osrm', cwd=d)
        run(OSRM_BIN / 'osrm-customize', 'ph.osrm', cwd=d)
        pbf.unlink()
        print(f'{period}: built in {(time.time() - t) / 60:.0f} min', flush=True)


# ---------------------------------------------------------------- tables

def origins() -> tuple[list[str], list[tuple[float, float]], dict[str, dict]]:
    feats = json.loads((ROOT / 'public' / 'data' / 'zonal.geojson').read_text(encoding='utf-8'))['features']
    ids, pts, props = [], [], {}
    for f in feats:
        if not f.get('geometry'):
            continue
        p = shape(f['geometry']).representative_point()
        ids.append(f['properties']['id'])
        pts.append((round(p.x, 5), round(p.y, 5)))
        props[f['properties']['id']] = f['properties']
    return ids, pts, props


def presets() -> list[dict]:
    with PRESETS.open(newline='', encoding='utf-8') as fh:
        return [{**r, 'lon': float(r['lon']), 'lat': float(r['lat'])} for r in csv.DictReader(fh)]


class Router:
    """osrm-routed on localhost for one period's dataset, for the duration of a `with` block."""

    def __init__(self, period: str):
        self.base = WORK / period / 'ph.osrm'

    def __enter__(self):
        self.proc = subprocess.Popen([str(OSRM_BIN / 'osrm-routed'), '--algorithm', 'mld', '--port', str(PORT),
                                      '--max-table-size', '10000', self.base.name], cwd=self.base.parent,
                                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        for _ in range(300):
            try:
                socket.create_connection(('127.0.0.1', PORT), timeout=1).close()
                return self
            except OSError:
                time.sleep(1)
        raise RuntimeError('osrm-routed did not start')

    def __exit__(self, *exc):
        self.proc.terminate()
        self.proc.wait()

    def table(self, srcs: list[tuple[float, float]], dsts: list[tuple[float, float]]) -> dict:
        coords = ';'.join(f'{x},{y}' for x, y in srcs + dsts)
        q = (f'sources={";".join(map(str, range(len(srcs))))}'
             f'&destinations={";".join(map(str, range(len(srcs), len(srcs) + len(dsts))))}'
             f'&annotations=duration,distance')
        with urllib.request.urlopen(f'http://127.0.0.1:{PORT}/table/v1/driving/{coords}?{q}', timeout=600) as r:
            res = json.loads(r.read())
        if res.get('code') != 'Ok':
            raise RuntimeError(res)
        return res


def _fields(buf: bytes):
    """(field number, value) pairs of a protobuf message; length-delimited values as bytes, varints as int."""
    i = 0
    while i < len(buf):
        key, i = _varint(buf, i)
        num, wire = key >> 3, key & 7
        if wire == 0:
            val, i = _varint(buf, i)
        elif wire == 2:
            n, i = _varint(buf, i)
            val, i = buf[i:i + n], i + n
        elif wire == 1:
            val, i = buf[i:i + 8], i + 8
        elif wire == 5:
            val, i = buf[i:i + 4], i + 4
        else:
            return
        yield num, val


def _varint(buf: bytes, i: int) -> tuple[int, int]:
    shift = val = 0
    while True:
        b = buf[i]
        i += 1
        val |= (b & 0x7f) << shift
        shift += 7
        if b < 0x80:
            return val, i


def network_date() -> str | None:
    """Replication timestamp in the extract's OSMHeader block (the date Geofabrik's data runs up to)."""
    import zlib
    with PBF.open('rb') as fh:
        size = int.from_bytes(fh.read(4), 'big')
        header = dict(_fields(fh.read(size)))
        blob = dict(_fields(fh.read(header[3])))
    data = zlib.decompress(blob[3]) if 3 in blob else blob.get(1, b'')
    ts = dict(_fields(data)).get(32)  # HeaderBlock.osmosis_replication_timestamp, seconds since 1970
    return datetime.fromtimestamp(ts, timezone.utc).date().isoformat() if ts else None


def snap_s(waypoint: dict) -> float:
    return waypoint['distance'] / (SNAP_KMH / 3.6)


def tables(chunk: int = 400) -> None:
    ids, pts, props = origins()
    dests = presets()
    dpts = [(d['lon'], d['lat']) for d in dests]
    # minutes[period][dest][i], plus road km for the sanity checks
    minutes = {p: [[None] * len(ids) for _ in dests] for p in PERIODS}
    km = {p: [[None] * len(ids) for _ in dests] for p in PERIODS}
    far_snaps = 0
    for period in PERIODS:
        t = time.time()
        with Router(period) as r:
            for s in range(0, len(ids), chunk):
                block = pts[s:s + chunk]
                if period == 'pm':  # destination -> barangay
                    res = r.table(dpts, block)
                    get = lambda j, i: (res['durations'][j][i], res['distances'][j][i],
                                        snap_s(res['sources'][j]) + snap_s(res['destinations'][i]))
                else:
                    res = r.table(block, dpts)
                    get = lambda j, i: (res['durations'][i][j], res['distances'][i][j],
                                        snap_s(res['sources'][i]) + snap_s(res['destinations'][j]))
                if period == 'am':
                    far_snaps += sum(w['distance'] > 1000 for w in res['sources'])
                for j in range(len(dests)):
                    for i in range(len(block)):
                        dur, dist, snap = get(j, i)
                        if dur is not None:
                            minutes[period][j][s + i] = round((dur + snap) / 60)
                            km[period][j][s + i] = dist / 1000
        print(f'{period}: {len(ids)} x {len(dests)} in {time.time() - t:.0f} s', flush=True)

    OUT.mkdir(parents=True, exist_ok=True)
    index = {
        'built_at': datetime.now(timezone.utc).isoformat(timespec='seconds'),
        'network': network_date(),
        'calibrated': False,
        'trips': 0,
        'range': RANGE,
        'mode': 'car',
        'periods': PERIODS,
        'presets': [{k: d[k] for k in ('id', 'name', 'group', 'lon', 'lat')} for d in dests],
        'ids': ids,
    }
    (OUT / 'index.json').write_text(json.dumps(index, separators=(',', ':'), ensure_ascii=False), encoding='utf-8')
    for j, d in enumerate(dests):
        (OUT / f"{d['id']}.json").write_text(json.dumps({p: minutes[p][j] for p in PERIODS}, separators=(',', ':')))
    print(f'wrote {OUT.relative_to(ROOT)}: index + {len(dests)} destinations; '
          f'{far_snaps} barangay centres more than 1 km from a routable road')
    report(ids, props, dests, minutes, km)


def report(ids, props, dests, minutes, km) -> None:
    """Checks to read, not to tune against: effective speeds next to published figures, and the motivating case."""
    j_of = {d['id']: j for j, d in enumerate(dests)}
    print('\nmedian effective speed, Metro Manila barangays to Makati / Ortigas / Manila '
          '(TomTom Traffic Index 2025, Manila city: 17.2 km/h morning rush, 13.8 evening):')
    for period in PERIODS:
        v = [km[period][j_of[k]][i] / (minutes[period][j_of[k]][i] / 60)
             for k in ('makati', 'ortigas', 'manila') for i, b in enumerate(ids)
             if props[b]['p'] == 'Metro Manila' and minutes[period][j_of[k]][i] and km[period][j_of[k]][i] > 2]
        print(f'  {period}: {statistics.median(v):.1f} km/h over {len(v)} trips')
    print('\nfrom Makati CBD in the evening peak (the trip home):')
    for name, city in (('Kapitolyo', 'Pasig'), ('San Antonio', 'Pasig'), ('Balibago', 'Santa Rosa'),
                       ('Dita', 'Santa Rosa'), ('Real', 'Calamba'), ('Molino III', 'Bacoor'),
                       ('Santo Niño', 'Marikina'), ('Bagong Silangan', 'Quezon City')):
        hit = [i for i, b in enumerate(ids) if props[b]['n'] == name and props[b]['c'] == city]
        for i in hit:
            m, k = minutes['pm'][j_of['makati']][i], km['pm'][j_of['makati']][i]
            print(f'  {name}, {city}: {m} min for {k:.0f} km' if m is not None else f'  {name}, {city}: no route')
    worst = sorted((m, ids[i]) for i, m in enumerate(minutes['am'][j_of['makati']]) if m is not None)[-3:]
    print('\nlongest morning trips to Makati:', ', '.join(f"{props[b]['n']}, {props[b]['c']} {m} min" for m, b in worst))
    none = sum(m is None for m in minutes['am'][j_of['makati']])
    if none:
        print(f'{none} barangays have no road route to Makati (islands or unconnected roads)')


def main() -> None:
    what = sys.argv[1] if len(sys.argv) > 1 else 'all'
    if what in ('build', 'all'):
        build()
    if what in ('table', 'all'):
        tables()


if __name__ == '__main__':
    main()
